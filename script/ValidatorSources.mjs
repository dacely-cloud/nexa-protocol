/** Emits the TypeScript sources generated from the gateway schema: the schema data, its validators and the method catalog. */
import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const HEADER =
    '// SPDX-FileCopyrightText: 2026 Dacely <business@dacely.com>\n// SPDX-License-Identifier: LicenseRef-Proprietary\n\n';
const NOTICE = 'Generated by script/generate.mjs from the package declarations; do not edit.';

/** Validator name, validated type and the module declaring it, for each contract root. */
function contractRoots() {
    const source = readFileSync(join(root, 'script/Contract.ts'), 'utf8');
    const modules = new Map();
    for (const match of source.matchAll(/import type \{([^}]*)\} from '\.\.\/src\/([^']+)';/gu)) {
        for (const name of match[1]
            .split(',')
            .map((item) => item.trim())
            .filter(Boolean)) {
            modules.set(name, match[2]);
        }
    }
    const roots = new Map();
    for (const match of source.matchAll(/readonly (\w+): ([^;]+);/gu)) {
        const type = match[2].trim();
        const named = /^(\w+)/u.exec(type)?.[1];
        const base = named === 'Omit' ? /^Omit<(\w+),/u.exec(type)?.[1] : named;
        if (base === undefined || !modules.has(base))
            throw new Error('Unresolved contract root type: ' + type);
        roots.set(match[1], { type, base, module: modules.get(base) });
    }
    return roots;
}

/** A gateway method name as a camel-case identifier stem. */
function stem(method) {
    const parts = method.split(/[.-]/u);
    return parts
        .map((part, index) => (index === 0 ? part : part[0].toUpperCase() + part.slice(1)))
        .join('');
}

/** A gateway method name as its catalog key. */
function key(method) {
    return method
        .split(/[.-]/u)
        .map((part) => part[0].toUpperCase() + part.slice(1))
        .join('');
}

/** Dependent checks that run after the shape check of particular method boundaries. */
const DEPENDENT = {
    'connectors.context.check': { result: 'ConnectorHostChecks.context' },
    'connectors.host.status': { result: 'ConnectorHostChecks.status' },
    'connectors.host.submit': {
        params: 'ConnectorHostChecks.submit',
        result: 'ConnectorHostChecks.job',
    },
    'connectors.host.result': { result: 'ConnectorHostChecks.job' },
    'connectors.workspace.select-host': { params: 'ConnectorHostChecks.select' },
    'connectors.workspace.get': { result: 'ConnectorHostChecks.workspace' },
    'connectors.instructions.update': {
        params: 'ConnectorInstructionsChecks.update',
        result: 'ConnectorInstructionsChecks.view',
    },
    'connectors.instructions.get': { result: 'ConnectorInstructionsChecks.view' },
    'connectors.inventory': {
        result: 'ConnectorInstructionsChecks.inventory',
        also: 'ConnectorHostChecks.inventory',
    },
};

/** Source generators for the schema modules. */
export class ValidatorSources {
    /** The schema module. */
    static schemaData(schema) {
        return (
            HEADER +
            "import type { Schema } from './Schema.js';\n\n" +
            `/**\n * The gateway schema every validator checks against. ${NOTICE}\n */\n` +
            `export const schema: Schema = ${JSON.stringify(schema, null, 2)};\n`
        );
    }

    /** The validator module: one validator per contract root and per method boundary. */
    static validators(schema) {
        const roots = contractRoots();
        const imports = new Map();
        const lines = [];
        for (const [name, entry] of Object.entries(schema.properties)) {
            const rootType = roots.get(name);
            if (rootType === undefined)
                throw new Error('Schema root missing from Contract.ts: ' + name);
            const module = '../' + rootType.module;
            if (!imports.has(module)) imports.set(module, new Set());
            imports.get(module).add(rootType.base);
            lines.push(
                `/** Validates a ${name} payload and narrows it to its declared type. */\n` +
                    `export function ${name}(value: unknown): value is ${rootType.type} {\n` +
                    `    return validator.validate(${JSON.stringify(entry.$ref)}, value);\n}`,
            );
        }
        for (const method of Object.keys(schema.definitions.GatewayMethods.properties)) {
            for (const side of ['params', 'result']) {
                const name = stem(method) + side[0].toUpperCase() + side.slice(1);
                const path = `#/definitions/GatewayMethods/properties/${method}/properties/${side}`;
                const dependent = DEPENDENT[method]?.[side];
                if (method === 'connectors.execution' && side === 'result') {
                    if (!imports.has('../dataplane/ConnectorExecutionTypes.js'))
                        imports.set('../dataplane/ConnectorExecutionTypes.js', new Set());
                    imports
                        .get('../dataplane/ConnectorExecutionTypes.js')
                        .add('ConnectorExecutionStatus');
                    lines.push(
                        `/** Shape validation precedes the dependent public permission checks. */\n` +
                            `function connectorsExecutionShape(value: unknown): value is ConnectorExecutionStatus {\n` +
                            `    return validator.validate(${JSON.stringify(path)}, value);\n}\n` +
                            `/** Validates complete bounded connector permission metadata. */\n` +
                            `export function ${name}(value: unknown): value is ConnectorExecutionStatus {\n` +
                            `    return connectorsExecutionShape(value) && ConnectorExecutionChecks.status(value);\n}`,
                    );
                    continue;
                }
                if (dependent !== undefined) {
                    const also = side === 'result' ? DEPENDENT[method].also : undefined;
                    lines.push(
                        `/** Validates the ${side} of \`${method}\`, then its dependent counters, grants and bounded text. */\n` +
                            `export function ${name}(value: unknown): boolean {\n` +
                            `    return validator.validate(${JSON.stringify(path)}, value) && ${dependent}(value)${also ? ` && ${also}(value)` : ''};\n}`,
                    );
                    continue;
                }
                lines.push(
                    `/** Validates the ${side} of \`${method}\`. */\n` +
                        `export function ${name}(value: unknown): boolean {\n` +
                        `    return validator.validate(${JSON.stringify(path)}, value);\n}`,
                );
            }
        }
        const typeImports = [...imports]
            .sort(([a], [b]) => a.localeCompare(b))
            .map(
                ([module, names]) =>
                    `import type { ${[...names].sort().join(', ')} } from '${module}';`,
            );
        return (
            HEADER +
            "import { ConnectorExecutionChecks } from './ConnectorExecutionChecks.js';\n" +
            "import { ConnectorHostChecks } from './ConnectorHostChecks.js';\n" +
            "import { ConnectorInstructionsChecks } from './ConnectorInstructionsChecks.js';\n" +
            "import { SchemaValidator } from './Schema.js';\n" +
            "import { schema } from './SchemaData.js';\n" +
            typeImports.join('\n') +
            '\n\n' +
            `/** ${NOTICE} */\nconst validator: SchemaValidator = new SchemaValidator(schema);\n\n` +
            '/** Validates untrusted JSON at a protocol boundary. */\nexport type Validator = (value: unknown) => boolean;\n\n' +
            lines.join('\n\n') +
            '\n'
        );
    }

    /** The exhaustive method boundary validator table. */
    static methodValidators(schema) {
        const methods = Object.keys(schema.definitions.GatewayMethods.properties);
        const names = methods
            .flatMap((method) => [stem(method) + 'Params', stem(method) + 'Result'])
            .sort();
        return (
            HEADER +
            `import type { MethodName } from '../gateway/ProtocolTypes.js';\n` +
            `import type { Validator } from './Validators.js';\n` +
            `import {\n${names.map((name) => '    ' + name + ',').join('\n')}\n} from './Validators.js';\n\n` +
            '/** The validators for one method boundary. */\n' +
            'export interface MethodValidation {\n    readonly params: Validator;\n    readonly result: Validator;\n}\n\n' +
            `/** Exhaustive gateway method boundary validators. ${NOTICE} */\n` +
            'export const methodValidators: Readonly<Record<MethodName, MethodValidation>> = {\n' +
            methods
                .map(
                    (method) =>
                        `    ${JSON.stringify(method)}: { params: ${stem(method)}Params, result: ${stem(method)}Result },`,
                )
                .join('\n') +
            '\n};\n'
        );
    }

    /**
     * The gateway method catalog. It stays the native enum the SDK published, so a raw method string is not a
     * method: callers name every call through the catalog.
     */
    static methods(schema) {
        const methods = Object.keys(schema.definitions.GatewayMethods.properties);
        const keys = new Set();
        const entries = methods.map((method) => {
            const name = key(method);
            if (!/^[A-Za-z][A-Za-z0-9]*$/u.test(name) || keys.has(name)) {
                throw new Error('Gateway method names require distinct identifiers: ' + method);
            }
            keys.add(name);
            return `    /** Calls \`${method}\`. */\n    ${name} = ${JSON.stringify(method)},`;
        });
        return (
            HEADER +
            `/**\n * Every gateway method, by name. ${NOTICE}\n */\n` +
            `export enum Method {\n${entries.join('\n')}\n}\n`
        );
    }
}
